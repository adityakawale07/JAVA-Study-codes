public class sumnum {

    public static void SUM(int num1,int num2)
    {
        int summ=num1+num2;
        System.out.println("The sum of two numbers is:"+summ);
    }
    public static void main(String[] args) {
        int num1=10;
        int num2=20;
        SUM(num1,num2);
    }
}
